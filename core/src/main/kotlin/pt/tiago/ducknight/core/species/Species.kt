package pt.tiago.ducknight.core.species

import kotlinx.serialization.Serializable

/** Speed classes. */
@Serializable
enum class SpeedClass(val speedUps: Int, val points: Int) {
    S1(48, 500),
    S2(62, 800),
    S3(78, 1_000),
    S4(95, 1_500),
    S5(112, 2_000),
    GOLDEN(104, 3_000),
}

/** Bird categories. Protected birds are never photographed. */
@Serializable
enum class SpeciesCategory {
    DABBLING,
    DIVING,
    GOOSE,
    GREBE,
    COOT,
    WADER_PROTECTED,
    LEGENDARY,
}

/** Body model used by the renderer. */
@Serializable
enum class BodyModel {
    DABBLING,
    DABBLING_SMALL,
    DIVING,
    DIVING_SLIM,
    GOOSE,
    GREBE,
    COOT,
    WADER,
    CROW,
}

/** Flight patterns. */
@Serializable
enum class FlightPattern {
    ZIGZAG,
    GLIDE,
    DART,
    CIRCLE,
    FORMATION,
    DIVE_SURFACE,
    TREE_HOP,
    BOSS,
}

/**
 * One species of the catalog. The simulated and the drawn bird read the same data.
 * Points default to the speed class table; a species may override them later.
 */
@Serializable
data class Species(
    val id: String,
    val nameEn: String,
    val namePt: String,
    val scientific: String,
    val category: SpeciesCategory,
    val body: BodyModel,
    val speedClass: SpeedClass,
    val radius: Int,
    val patterns: List<FlightPattern>,
    val dives: Boolean = false,
    val protected: Boolean = false,
    val firstPlace: Int = 1,
    val points: Int = speedClass.points,
) {
    init {
        require(id.isNotBlank()) { "Species id must not be blank" }
        require(radius in 8..16) { "Species $id radius $radius outside 8..16" }
        require(patterns.isNotEmpty()) { "Species $id needs a flight pattern" }
        require(points > 0) { "Species $id needs positive points" }
    }
}

